/**
 * One-off generator: resolves an artwork URL for every roster entry and bakes
 * it into src/data/pokemon.artwork.generated.ts.
 *
 * v1 fetched /pokemon/{slug} at the end of every round purely to read a sprite
 * URL out of the response, so the result modal showed "Loading render..." while
 * a JSON round trip completed before the image could even start downloading.
 *
 * Run with: node scripts/generate-artwork-data.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const dataDir = path.join(__dirname, '..', 'src', 'data')
const outputPath = path.join(dataDir, 'pokemon.artwork.generated.ts')

const concurrency = 20

const formModifierWords = new Set([
  'mega', 'x', 'y', 'z', 'primal', 'alola', 'cap', 'galar', 'hisui', 'paldea',
  'totem', 'original', 'color', 'curly', 'droopy', 'stretchy', 'form',
  'blaze', 'aqua', 'combat', 'three', 'segment',
])

function toPokemonSlug(name) {
  return name
    .replace(/♀/g, '-f')
    .replace(/♂/g, '-m')
    .replace(/['’]/g, '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function getBaseSpeciesSlug(name) {
  const words = name.trim().split(/\s+/)

  while (words.length > 1 && formModifierWords.has(words[words.length - 1].toLowerCase())) {
    words.pop()
  }

  return toPokemonSlug(words.join(' '))
}

async function readRosterNames() {
  const files = ['pokemon.generated.ts', 'pokemon.variants.generated.ts']
  const names = []

  for (const file of files) {
    const source = await readFile(path.join(dataDir, file), 'utf8')

    for (const match of source.matchAll(/name['"]?\s*:\s*['"]([^'"]+)['"]/g)) {
      names.push(match[1])
    }
  }

  return [...new Set(names)]
}

function pickArtwork(pokemonData) {
  return (
    pokemonData?.sprites?.other?.['official-artwork']?.front_default ??
    pokemonData?.sprites?.other?.home?.front_default ??
    pokemonData?.sprites?.front_default ??
    null
  )
}

async function fetchArtwork(slug) {
  const response = await fetch(`https://pokeapi.co/api/v2/pokemon/${slug}`)

  if (!response.ok) {
    return null
  }

  return pickArtwork(await response.json())
}

/**
 * Several species are only addressable via a form-suffixed variety name
 * (Deoxys -> deoxys-normal, Giratina -> giratina-altered, and so on). The
 * species resource lists its varieties, so we can resolve the default one
 * instead of hardcoding a suffix table.
 */
async function fetchArtworkViaDefaultVariety(baseSlug) {
  const response = await fetch(`https://pokeapi.co/api/v2/pokemon-species/${baseSlug}`)

  if (!response.ok) {
    return null
  }

  const species = await response.json()
  const varieties = Array.isArray(species?.varieties) ? species.varieties : []
  const preferred = varieties.find((variety) => variety?.is_default) ?? varieties[0]
  const varietyName = preferred?.pokemon?.name

  return varietyName ? fetchArtwork(varietyName) : null
}

async function main() {
  const names = await readRosterNames()
  console.log(`Roster entries: ${names.length}`)

  const result = {}
  const unresolved = []
  let index = 0
  let done = 0

  async function worker() {
    while (index < names.length) {
      const name = names[index++]
      const exactSlug = toPokemonSlug(name)
      const baseSlug = getBaseSpeciesSlug(name)

      try {
        // Prefer the exact form's artwork (Mega Charizard X looks different
        // from Charizard), falling back to the base species for the roster's
        // non-canonical forms that PokeAPI has never heard of.
        let artwork = await fetchArtwork(exactSlug)

        if (!artwork && baseSlug !== exactSlug) {
          artwork = await fetchArtwork(baseSlug)
        }

        if (!artwork) {
          artwork = await fetchArtworkViaDefaultVariety(baseSlug)
        }

        if (artwork) {
          result[name] = artwork
        } else {
          unresolved.push(name)
        }
      } catch (error) {
        unresolved.push(`${name} (${error.message})`)
      }

      done += 1

      if (done % 200 === 0) {
        console.log(`  ${done}/${names.length}`)
      }
    }
  }

  await Promise.all(Array.from({ length: concurrency }, () => worker()))

  const header = `// Generated by scripts/generate-artwork-data.mjs — do not edit by hand.
// Official artwork URL per roster entry, resolved once so the result screen can
// start loading the image immediately instead of waiting on an API round trip.
export const pokemonArtwork: Record<string, string> = `

  await writeFile(outputPath, `${header}${JSON.stringify(result, null, 2)}\n`, 'utf8')

  console.log(`\nWrote ${Object.keys(result).length} artwork URLs`)

  if (unresolved.length > 0) {
    console.warn(`${unresolved.length} entries had no artwork:`, unresolved.slice(0, 20))
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
